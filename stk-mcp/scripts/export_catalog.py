"""Export the Python tool catalog for the DSH TypeScript plugin.

Run from the repository root:

    python stk-mcp/scripts/export_catalog.py

The DSH plugin imports the generated ``catalog.ts`` so its schemas cannot drift
from the MCP/REST catalog. ``tools.json`` is the language-neutral contract.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
STK_ROOT = ROOT / "stk-mcp"
sys.path.insert(0, str(STK_ROOT / "src"))

from spaceone_stk_mcp.registry import catalog  # noqa: E402

CURATED = [
    "stk_connect",
    "stk_status",
    "scenario_create",
    "scenario_info",
    "scenario_set_time",
    "satellite_create",
    "satellite_set_orbit",
    "satellite_state",
    "satellite_ephemeris",
    "facility_create",
    "sensor_create",
    "access_compute",
    "coverage_create",
    "coverage_set_grid",
    "coverage_add_asset",
    "coverage_remove_asset",
    "coverage_compute",
    "coverage_stats",
    "coverage_fom_create",
    "coverage_fom_query",
    "coverage_grid_inspector",
    "data_provider_list",
    "data_provider_query",
    "report_create",
    "object_list",
    "equipment_create",
    "equipment_configure",
    "equipment_list",
    "platform_create",
    "platform_set_waypoints",
    "area_target_create",
    "area_target_set_polygon",
    "chain_create",
    "chain_compute_access",
    "constellation_build_walker",
    "astrogator_summary",
    "astrogator_run",
    "report_list_styles",
    "stk_execute_command",
    "stk_selftest",
]

DSH_PREFIX = "stk_"


def dsh_name(operation: str) -> str:
    if operation.startswith("stk_"):
        return operation
    return DSH_PREFIX + operation


def main() -> int:
    data = catalog()
    by_name = {tool["name"]: tool for tool in data["tools"]}
    missing = [name for name in CURATED if name not in by_name]
    if missing:
        raise SystemExit(f"Curated tools missing from catalog: {missing}")

    contracts = STK_ROOT / "contracts"
    contracts.mkdir(parents=True, exist_ok=True)
    (contracts / "tools.json").write_text(
        json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )

    curated = []
    for operation in CURATED:
        tool = by_name[operation]
        curated.append(
            {
                "name": dsh_name(operation),
                "operation": operation,
                "description": tool["description"],
                "parameters": tool["parameters"],
                "category": tool["category"],
                "mutating": tool["mutating"],
            }
        )
    all_tools = [
        {
            "name": dsh_name(tool["name"]),
            "operation": tool["name"],
            "description": tool["description"],
            "parameters": tool["parameters"],
            "category": tool["category"],
            "mutating": tool["mutating"],
        }
        for tool in data["tools"]
    ]

    target = ROOT / "spaceone-stk-plugin" / "src" / "generated" / "catalog.ts"
    target.parent.mkdir(parents=True, exist_ok=True)
    header = (
        "/* AUTO-GENERATED by spaceone-stk-mcp/scripts/export_catalog.py. Do not edit. */\n"
        "export type JsonSchema = Record<string, unknown>;\n\n"
        "export interface CatalogTool {\n"
        "  name: string;\n"
        "  operation: string;\n"
        "  description: string;\n"
        "  parameters: JsonSchema;\n"
        "  category: string;\n"
        "  mutating: boolean;\n"
        "}\n\n"
    )
    body = (
        "export const CURATED_TOOLS: CatalogTool[] = "
        + json.dumps(curated, ensure_ascii=False, indent=2)
        + ";\n\n"
        + "export const ALL_TOOLS: CatalogTool[] = "
        + json.dumps(all_tools, ensure_ascii=False, indent=2)
        + ";\n"
    )
    target.write_text(header + body, encoding="utf-8")
    print(f"Wrote {target} ({len(curated)} curated, {len(all_tools)} total)")
    print(f"Wrote {contracts / 'tools.json'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
